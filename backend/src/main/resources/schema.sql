CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS login_sessions (
 token_hash VARCHAR(64) PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS experiences (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 type VARCHAR(255) NOT NULL,
 content VARCHAR(3000) NOT NULL,
 category VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6),
 details CLOB
);
CREATE INDEX IF NOT EXISTS experience_owner_created ON experiences(owner_id,created_at,id);
CREATE TABLE IF NOT EXISTS checklist_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 experience_id BIGINT NOT NULL REFERENCES experiences(id) ON DELETE CASCADE,
 content VARCHAR(1000) NOT NULL,
 sort_order INTEGER NOT NULL,
 status ENUM('COMPLETED','IN_PROGRESS','NOT_APPLICABLE','NOT_STARTED') NOT NULL,
 updated_at TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS checklist_experience ON checklist_items(experience_id);
CREATE TABLE IF NOT EXISTS prevention_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 experience_id BIGINT NOT NULL REFERENCES experiences(id) ON DELETE CASCADE,
 category VARCHAR(255) NOT NULL,
 content VARCHAR(1000) NOT NULL,
 trigger_point VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS prevention_experience ON prevention_rules(experience_id);
