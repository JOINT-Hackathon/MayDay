const prompts = {
  facts: '직접 본 문구나 파일에서 확인한 내용을 한 가지 적어 주세요. 아직 확인하지 못했다면 “아직 직접 확인한 사실 없음”이라고 적어도 괜찮아요.',
  unknown: '아직 모르는 항목을 하나 골라 주세요. 예: 받은 사람이 파일을 사용했는지. 없다면 “추가 확인할 사항 없음”이라고 적어 주세요.',
  improvement: '언제 무엇을 할지 정해 볼까요? 예: 오늘 업무 시작 전에 보낸 메일의 첨부파일을 열어 버전을 확인하기.',
  followUp: '누구에게 무엇을 물을까요? 예: 오늘 팀장님께 기존 파일 사용 여부를 묻기. 보고가 필요 없다면 이유를 적어 주세요.',
  checklist: '다음 업무의 어느 시점에 무엇을 확인할까요? 예: 메일 발송 직전 첨부파일을 열어 날짜와 버전을 확인하기.',
};

export function clarificationFor(key, value) {
  if (!prompts[key]) return '';
  const text = value.trim().replace(/[.!?…~ㅠㅜ\s]/g, '');
  // shortcut: 흔한 모호한 답변만 감지하며, 다양한 표현의 의미 판단이 필요하면 AI 질문을 사용한다.
  return !text || /^(모르겠|모르|몰라|글쎄|아무거나|그냥|잘할|잘하겠|열심히|조심할|주의할|확인할게|네$|응$|없어요$)/.test(text)
    ? prompts[key] : '';
}
